// plan-decisions.mjs: record a decision for every row of the site-reforge change-control ledger (audit/change-control.json),
// by rule, each with its reason, then regenerate docs/CHANGE-LOG.md. Equivalent to `sr-plan --set` per row.
//   node tools/plan-decisions.mjs [--dist dist]
// A row whose page is rebuilt at the same URL is PRESERVE (its words are rendered from the capture); app and calendar
// views are REMOVE with the reason; archive/pagination views are REPLACE; placeholder text is REMOVE. Narrative slots
// are mapped on the home page rows.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const DIST = path.join(ROOT, args.includes('--dist') ? args[args.indexOf('--dist') + 1] : 'dist');
const F = path.join(ROOT, 'audit/change-control.json');
const led = JSON.parse(fs.readFileSync(F, 'utf8'));
const ORIGIN = 'https://capitaldistrictcannabis.com';
const built = (p) => { const rel = p.replace(/^\//, '').replace(/\/?$/, '/'); const f = path.join(DIST, rel === '/' ? '' : rel, 'index.html'); return fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : null; };
const PLACEHOLDER = /lorem ipsum|happy little bushes|at nulla enim|maecenas mauris|auctor maecenas|malesuada porttitor/i;
const HOME_SLOTS = [
  [/unifying|building community|shop now|our mission/i, 'value-proposition'],
  [/shop by category|flower|pre-rolls|edibles|vapes|concentrates|tinctures|beverages|accessories/i, 'benefits-solution'],
  [/our purpose|different experience|about us|locations/i, 'trust-positioning'],
  [/review/i, 'social-proof'],
  [/faq|licensed|benefits of buying|types of cannabis|recreational cannabis legal|resident|how much cannabis/i, 'objection-handling'],
  [/news ?letter|sign up/i, 'strategic-cta'],
  [/find a store|albany|clifton|schenectady|switch your store|menu/i, 'footer'],
];
const counts = {};
// rows this script adds (the hero and the new pages) are regenerated on every run, never re-decided
led.rows = led.rows.filter((r) => !String(r.id).startsWith('new:') && r.id !== 'capitaldistrictcannabis.com/#hero');
for (const r of led.rows) {
  const p = (r.url || '').replace(ORIGIN, '') || '/';
  let d = 'PRESERVE', why = '', slot = '', as = '';
  if (/^\/stores(\/|$)|^\/product\//.test(p)) { d = 'REMOVE'; why = 'Live menu application (products, specials, cart, checkout): not rebuilt. Every Shop, Specials and category button links straight to it, store by store.'; }
  else if (/^\/events\/./.test(p)) { d = 'REMOVE'; why = 'Calendar view (list, month, day, category) generated by the events plugin; each event is rebuilt at its own /event/<slug>/ URL and listed with filters on /events/.'; }
  else if (/^\/(author|page)\/|^\/blog\/(page|category)\//.test(p)) { d = 'REPLACE'; why = 'Archive or pagination view: the posts are listed on /blog/ with category filters and on each category archive page.'; as = '/blog/'; }
  else if (/^\/(find-a-dispensary|albany)$/.test(p)) { d = 'REPLACE'; why = 'Empty page on the live site; forwards to ' + (p === '/albany' ? '/location/albany/' : '/store-locator/') + '.'; as = p === '/albany' ? '/location/albany/' : '/store-locator/'; }
  else if (PLACEHOLDER.test(r.label || '')) { d = 'REMOVE'; why = 'Placeholder text on the live site (lorem ipsum / template copy), not client content.'; }
  else {
    const html = built(p);
    if (!html) { d = 'REPLACE'; why = 'Rebuilt page not found at this URL in the build; see docs/PITCH-NOTES.md.'; }
    else { d = 'PRESERVE'; why = 'Rebuilt at the same URL; the words render from the capture (src/content/capture.json), restyled in the new design.'; as = p === '/' ? '/' : p + '/'; }
  }
  if (p === '/' && d === 'PRESERVE') { const m = HOME_SLOTS.find(([re]) => re.test(r.label || '')); slot = m ? m[1] : 'benefits-solution'; d = 'IMPROVE'; why = 'Home section kept with its words and rebuilt in the new design (see docs/DESIGN.md).'; }
  r.decision = d; r.why = why; r.narrativeSlot = slot || r.narrativeSlot || ''; r.rebuiltAs = as;
  counts[d] = (counts[d] || 0) + 1;
}
// the live home hero ("Building Community Through Cannabis" / "Unifying Upstate" / Shop Now / Our Mission) is a real
// section the ledger's splitter missed (it split the home page on the mobile-nav accordion); record it so the
// value-proposition slot maps to the section that carries it
if (!led.rows.some((r) => r.id === 'capitaldistrictcannabis.com/#hero')) {
  led.rows.unshift({ id: 'capitaldistrictcannabis.com/#hero', url: ORIGIN + '/', pageType: 'home', index: 0, label: 'Unifying Upstate (hero: kicker, H1, Shop Now, Our Mission)', sourceTag: 'module-hero', sourceClass: 'module-hero', decision: 'IMPROVE', why: 'Home hero kept word for word (kicker, H1, both buttons) and rebuilt as the skyline-after-dark hero with the record and the store sleeve (docs/DESIGN.md).', narrativeSlot: 'value-proposition', presetId: '', rebuiltAs: '/' });
  counts.IMPROVE = (counts.IMPROVE || 0) + 1;
}
// the new page types are ADD rows
const NEW = [['/shop/', 'Shop hub: store chooser, category crate straight to the live menu, ordering steps', 'benefits-solution'],
  ['/deals/', 'Specials by store, each linking to that store\'s live specials', 'strategic-cta'],
  ['/how-to-order/', 'Ordering flow explained step by step', 'objection-handling'],
  ['/pickup/', 'What happens at pickup: ID, payment, limits, store notes', 'objection-handling'],
  ['/learn/', 'Cannabis 101 education hub built from the site\'s own FAQs and articles', 'trust-positioning'],
  ['/faq/', 'Every FAQ answer on the site in one place', 'objection-handling'],
  ['/reviews/', 'Every review published on the site in one place', 'social-proof'],
  ['/sitemap/', 'HTML site map', 'footer']];
for (const [u, label, slot] of NEW) { if (!built(u)) continue; led.rows.push({ id: 'new:' + u, url: ORIGIN + u, pageType: 'new', index: 0, label, sourceTag: 'new', sourceClass: '', decision: 'ADD', why: 'New page type adopted from the reference information architecture; copy written from the live site\'s facts only (client approval pending).', narrativeSlot: slot, presetId: '', rebuiltAs: u }); counts.ADD = (counts.ADD || 0) + 1; }
led.rowCount = led.rows.length; led.updated = new Date().toISOString();
fs.writeFileSync(F, JSON.stringify(led, null, 2));
// docs/CHANGE-LOG.md, summarised by decision and page group (the full ledger stays in audit/change-control.json)
const group = (u) => { const p = u.replace(ORIGIN, '') || '/'; return p === '/' ? '/' : '/' + p.split('/')[1] + '/'; };
const agg = {};
for (const r of led.rows) { const k = group(r.url) + ' | ' + r.decision; agg[k] = agg[k] || { n: 0, why: r.why }; agg[k].n++; }
const md = `# Change log\n\nGenerated by \`tools/plan-decisions.mjs\` from the change-control ledger (\`audit/change-control.json\`, ${led.rows.length} rows: one per section of every captured page, plus the new pages). Totals: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(', ')}.\n\n| page group | decision | rows | reason |\n|---|---|---|---|\n${Object.entries(agg).sort().map(([k, v]) => { const [g, dd] = k.split(' | '); return `| \`${g}\` | ${dd} | ${v.n} | ${v.why.replace(/\|/g, '/')} |`; }).join('\n')}\n`;
fs.writeFileSync(path.join(ROOT, 'docs/CHANGE-LOG.md'), md);
console.log('ledger rows', led.rows.length, counts);
